function printInfo()
	wepByte = emu.read(0x5D, emu.memType.nesInternalRam)
	wepBinary = ""
	for i = 7, 0, -1 do
		wepBinary = wepBinary .. tostring((wepByte >> i) & 1)
	end
	weapon = emu.read(0x5F, emu.memType.nesInternalRam, true)
	bulletPresent = emu.read(0x60, emu.memType.nesInternalRam, true)
	pause = emu.read(0x42, emu.memType.nesInternalRam, true)
	yPos = emu.read(0x25, emu.memType.nesInternalRam, true)
	level = emu.read(0x31, emu.memType.nesInternalRam, true)
	emu.drawString(0, 0, weapon, 0xFFFFFF)
	emu.drawString(0, 10, timer, 0xFFFFFF)
	emu.drawString(0, 20, bulletPresent, 0xFFFFFF)
	emu.drawString(0, 30, pause, 0xFFFFFF)
	emu.drawString(0, 40, yPos, 0xFFFFFF)
	emu.drawString(0, 50, wepBinary, 0xFFFFFF)
	emu.drawString(0, 60, "MFCIGEBP", 0xFFFFFF)
	emu.drawString(0, 70, level, 0xFFFFFF)
end

function inputTest()
	timer = timer - 1
	if timer < 0 then
		timer = 0
	end
	if emu.isKeyPressed("S") and timer == 0 and bulletPresent == 0 and pause == 5 and yPos ~= 0 then
		checkLockedWepRight()
		timer = 10
		weapon = weapon + 1
		if weapon >= 8 then
			weapon = 0
		end
		emu.write(0x5F, weapon, emu.memType.nesInternalRam)
	end
	if emu.isKeyPressed("A") and timer == 0 and bulletPresent == 0 and pause == 5 and yPos ~= 0 then
		checkLockedWepLeft()
		timer = 10
		weapon = weapon - 1
		if weapon <= -1 then
			weapon = 7
		end
		emu.write(0x5F, weapon, emu.memType.nesInternalRam)
	end
end

function checkLockedWepLeft()
	if weapon == 0 and (wepByte & 0x80) == 0 then
		weapon = 7
	end
	if weapon == 7 and (wepByte & 0x08) == 0 then
		weapon = 6
	end
	if weapon == 6 and (wepByte & 0x04) == 0 then
		weapon = 5
	end
	if weapon == 5 and (wepByte & 0x40) == 0 then
		weapon = 4
	end
	if weapon == 4 and (wepByte & 0x02) == 0 then
		weapon = 3
	end
	if weapon == 3 and (wepByte & 0x10) == 0 then
		weapon = 2
	end
	if weapon == 2 and (wepByte & 0x20) == 0 then
		weapon = 1
	end
end

function checkLockedWepRight()
	if weapon == 0 and (wepByte & 0x20) == 0 then
		weapon = 1
	end
	if weapon == 1 and (wepByte & 0x10) == 0 then
		weapon = 2
	end
	if weapon == 2 and (wepByte & 0x02) == 0 then
		weapon = 3
	end
	if weapon == 3 and (wepByte & 0x40) == 0 then
		weapon = 4
	end
	if weapon == 4 and (wepByte & 0x04) == 0 then
		weapon = 5
	end
	if weapon == 5 and (wepByte & 0x08) == 0 then
		weapon = 6
	end
	if weapon == 6 and (wepByte & 0x80) == 0 then
		weapon = 7
	end
end

