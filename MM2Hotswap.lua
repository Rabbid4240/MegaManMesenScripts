function inputTest()
	timer = timer - 1
	if timer < 0 then
		timer = 0
	end
	if emu.isKeyPressed("A") and timer == 0 and (spriteFlag0 & 0x80) == 0 and (spriteFlag1 & 0x80) == 0 and (spriteFlag2 & 0x80) == 0 and (spriteFlag3 & 0x80) == 0 and (spriteFlag4 & 0x80) == 0 and gameState == 14 then
		checkLockedWepLeft()
		timer = 10
		weapon = weapon - 1
		if weapon <= -1 then
			weapon = 11
		end
		emu.write(0xA9, weapon, emu.memType.nesInternalRam)
		changeColor()
	end
	if emu.isKeyPressed("S") and timer == 0 and (spriteFlag0 & 0x80) == 0 and (spriteFlag1 & 0x80) == 0 and (spriteFlag2 & 0x80) == 0 and (spriteFlag3 & 0x80) == 0 and (spriteFlag4 & 0x80) == 0 and gameState == 14 then
		checkLockedWepRight()
		timer = 10
		weapon = weapon + 1
		if weapon >= 12 then
			weapon = 0
		end
		emu.write(0xA9, weapon, emu.memType.nesInternalRam)
		changeColor()
	end
end

function checkLockedWepLeft()
	if weapon == 0 and (itemByte & 0x04) == 0 then
		weapon = 11
	end
	if weapon == 11 and (itemByte & 0x02) == 0 then
		weapon = 10
	end
	if weapon == 10 and (itemByte & 0x01) == 0 then
		weapon = 9
	end
	if weapon == 9 and (wepByte & 0x80) == 0 then
		weapon = 8
	end
	if weapon == 8 and (wepByte & 0x40) == 0 then
		weapon = 7
	end
	if weapon == 7 and (wepByte & 0x20) == 0 then
		weapon = 6
	end
	if weapon == 6 and (wepByte & 0x10) == 0 then
		weapon = 5
	end
	if weapon == 5 and (wepByte & 0x08) == 0 then
		weapon = 4
	end
	if weapon == 4 and (wepByte & 0x04) == 0 then
		weapon = 3
	end
	if weapon == 3 and (wepByte & 0x02) == 0 then
		weapon = 2
	end
	if weapon == 2 and (wepByte & 0x01) == 0 then
		weapon = 1
	end
end

function checkLockedWepRight()
	if weapon == 0 and (wepByte & 0x01) == 0 then
		weapon = 1
	end
	if weapon == 1 and (wepByte & 0x02) == 0 then
		weapon = 2
	end
	if weapon == 2 and (wepByte & 0x04) == 0 then
		weapon = 3
	end
	if weapon == 3 and (wepByte & 0x08) == 0 then
		weapon = 4
	end
	if weapon == 4 and (wepByte & 0x10) == 0 then
		weapon = 5
	end
	if weapon == 5 and (wepByte & 0x20) == 0 then
		weapon = 6
	end
	if weapon == 6 and (wepByte & 0x40) == 0 then
		weapon = 7
	end
	if weapon == 7 and (wepByte & 0x80) == 0 then
		weapon = 8
	end
	if weapon == 8 and (itemByte & 0x01) == 0 then
		weapon = 9
	end
	if weapon == 9 and (itemByte & 0x02) == 0 then
		weapon = 10
	end
	if weapon == 10 and (itemByte & 0x04) == 0 then
		weapon = 11
	end
end

